def validate_against_lexicon(slot_bare: dict[str, list[str]]) -> list[str]:
    """确认所有服装池的取值（裸词）都真实存在于词库中。

    词库改动后必须跑这个，否则池子里会出现词库里没有的词。
    传入的是 lexicon.json 的 slot_bare（已剥掉「配色/材质/刺绣」后缀）。
    """
    errs = []
    for tone, slots in COSTUME_POOL.items():
        for slot, vals in slots.items():
            real = set(slot_bare.get(slot, []))
            for v in vals:
                if v not in real:
                    errs.append(f"{tone}/{slot}: 「{v}」不在词库中")
    return errs


def unused_values(slot_bare: dict[str, list[str]]) -> dict[str, list[str]]:
    """列出词库里存在、但五个调性都没用到的裸词。"""
    out = {}
    for slot in SLOTS:
        real = set(slot_bare.get(slot, []))
        used = set()
        for tone in COSTUME_POOL:
            used |= set(COSTUME_POOL[tone].get(slot, []))
        if real - used:
            out[slot] = sorted(real - used)
    return out
