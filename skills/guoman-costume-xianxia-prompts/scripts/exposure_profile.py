def pose_options(tone: str) -> list[str]:
    """某调性下所有可选姿势（构图 + 动作）。"""
    out: list[str] = []
    try:
        from . import tone_profile as TP  # type: ignore
    except Exception:
        import tone_profile as TP  # type: ignore
    out += list(TP.POSE_POOL.get(tone, []))
    out += COMPOSE_POSE_EXTRA.get(tone, [])
    out += ACTION_POSE.get(tone, [])
    return out


def is_action_pose(pose: str) -> bool:
    """动作姿态没有「以…姿态…画面」的构图句式，拼装时不做首句主结构。"""
    for items in ACTION_POSE.values():
        if pose in items:
            return True
    return False
