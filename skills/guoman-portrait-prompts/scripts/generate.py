CATEGORY_ORDER = ["传统旗袍", "迷你旗袍", "迷你礼裙", "迷你包臀裙", "长款礼裙"]


# ---------------------------------------------------------------- 组装
def build(age, temper, hair, outfit, detail, sexy, pose, scene, light):
    return (f"{STYLE_OPEN}{age}{temper}，{hair}。身着{outfit}，{detail}，"
            f"精致的东方面容。{sexy}。{pose}。场景：{scene}。{light}。")


def generate(n, seed=None, lock=None):
    """批量生成 n 条提示词。

    lock: dict，锁定指定字段不再随机。
        可用键：age / temper / hair / outfit_cat / outfit / sexy / pose / scene / light
        outfit / scene / light 可只给子串，做模糊匹配。
    """
    lock = {k: v for k, v in (lock or {}).items() if v}
    rng = random.Random(seed)
    used_full = set()
    used_triple = set()
    out = []
    tries = 0
    max_tries = n * 200

    locked_cat = lock.get("outfit_cat") or ""

    while len(out) < n and tries < max_tries:
        tries += 1
        idx = len(out)
        if locked_cat and locked_cat in OUTFITS:
            cat = locked_cat
        else:
            cat = CATEGORY_ORDER[idx % len(CATEGORY_ORDER)]  # 五类均衡轮换

        age = lock.get("age") or rng.choice(AGES)
        temper = lock.get("temper") or rng.choice(TEMPERS)
        hair = lock.get("hair") or rng.choice(HAIRS)

        # 服装：锁定单条时模糊匹配，否则在类别里随机
        outfit_lock = lock.get("outfit") or ""
        if outfit_lock:
            pool = [o for o in OUTFITS[cat] if outfit_lock in o[0]]
            if not pool:
                pool = [o for cat2 in OUTFITS.values() for o in cat2 if outfit_lock in o[0]]
            outfit, detail = rng.choice(pool) if pool else rng.choice(OUTFITS[cat])
        else:
            outfit, detail = rng.choice(OUTFITS[cat])

        sexy = lock.get("sexy") or rng.choice(SEXY)
        pose = lock.get("pose") or rng.choice(POSES)

        # 场景与光线成对；锁定场景时在该场景候选里挑光线
        scene_lock = lock.get("scene") or ""
        light_lock = lock.get("light") or ""
        if scene_lock:
            cands = [s for s in SCENES if scene_lock in s[0]] or SCENES
            if light_lock:
                cands = [s for s in cands if light_lock in s[1]] or cands
            scene, light = rng.choice(cands)
        elif light_lock:
            cands = [s for s in SCENES if light_lock in s[1]] or SCENES
            scene, light = rng.choice(cands)
        else:
            scene, light = rng.choice(SCENES)

        line = build(age, temper, hair, outfit, detail, sexy, pose, scene, light)
        if not validate(line):
            continue
        if line in used_full:
            continue
        triple = (outfit, scene, pose)
        if triple in used_triple:
            continue

        used_full.add(line)
        used_triple.add(triple)
        out.append({
            "id": idx + 1,
            "category": cat,
            "prompt": line,
            "elements": {
                "age": age, "temper": temper, "hair": hair,
                "outfit": outfit, "detail": detail, "sexy": sexy,
                "pose": pose, "scene": scene, "light": light,
            },
        })
    return out

def main():
    ap = argparse.ArgumentParser(description="国漫/东方女性人像提示词批量生成器（二次元厚涂御姐线）")
    ap.add_argument("-n", "--num", type=int, default=20, help="生成条数，默认 20")
    ap.add_argument("-o", "--out", help="输出 txt 路径")
    ap.add_argument("--json", help="输出 json 路径（含元素拆解）")
    ap.add_argument("--seed", type=int, default=None, help="随机种子，便于复现")
    # 锁定参数：传了就固定该字段，不传就随机
    ap.add_argument("--age", help="锁定年龄，如 25岁")
    ap.add_argument("--temper", help="锁定人物类型，如 成熟御姐")
    ap.add_argument("--hair", help="锁定发型（子串匹配）")
    ap.add_argument("--outfit-cat", help="锁定服装类别，如 传统旗袍")
    ap.add_argument("--outfit", help="锁定服装（子串匹配）")
    ap.add_argument("--sexy", help="锁定性感级别（子串匹配）")
    ap.add_argument("--pose", help="锁定姿势（子串匹配）")
    ap.add_argument("--scene", help="锁定场景（子串匹配）")
    ap.add_argument("--light", help="锁定光线（子串匹配）")
    args = ap.parse_args()

    if args.num <= 0:
        print("条数必须为正整数", file=sys.stderr)
        return 1

    lock = {
        "age": getattr(args, "age", None),
        "temper": getattr(args, "temper", None),
        "hair": getattr(args, "hair", None),
        "outfit_cat": getattr(args, "outfit_cat", None),
        "outfit": getattr(args, "outfit", None),
        "sexy": getattr(args, "sexy", None),
        "pose": getattr(args, "pose", None),
        "scene": getattr(args, "scene", None),
        "light": getattr(args, "light", None),
    }
    rows = generate(args.num, args.seed, lock=lock)

    if len(rows) < args.num:
        print(f"注意：词池组合空间不足，实际生成 {len(rows)} / {args.num} 条", file=sys.stderr)

    lines = [f"{r['id']}.{r['prompt']}" for r in rows]
    text = "\n\n".join(lines)

    if args.out:
        Path(args.out).write_text(text + "\n", encoding="utf-8")
        print(f"已写入 {args.out}（{len(rows)} 条）")
    else:
        print(text)

    if args.json:
        Path(args.json).write_text(
            json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        print(f"已写入 {args.json}")

    # 自检摘要
    bad = [r for r in rows if not validate(r["prompt"])]
    print(f"自检：{len(rows)} 条，违规 {len(bad)} 条", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
